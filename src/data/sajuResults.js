export function selectResult(genre, gender, month, day, ohengCount, ilju) {
  const getSeason = (m) => {
    if (m >= 3 && m <= 5) return '봄'
    if (m >= 6 && m <= 8) return '여름'
    if (m >= 9 && m <= 11) return '가을'
    return '겨울'
  }

  const season = getSeason(month)
  const mainOheng = Object.entries(ohengCount).sort((a,b)=>b[1]-a[1])[0][0]
  const danceInfo = OHENG_DANCE[mainOheng]
  const seasonMsgs = SEASON_MSGS[season]
  const seasonMsg = seasonMsgs[(day + month) % seasonMsgs.length]
  const iljuData = ILJU_MSGS[ilju] || { title: `${ilju}일주`, msg: `${ilju}일주의 특별한 기운이 댄스에서 빛납니다.` }
  const genderExprs = GENDER_EXPR[gender] || GENDER_EXPR['남']
  const genderTrait = genderExprs[(day * month) % genderExprs.length]
  const ohengName = { '木': '나무', '火': '불', '土': '흙', '金': '쇠', '水': '물' }[mainOheng]

  const title = `${iljuData.title} — ${gender === '남' ? '리더' : '아티스트'}의 운명`

  const desc = `${iljuData.msg}

본 분석은 만세력(萬歲曆) 기반 정통 사주명리학으로 산출되었습니다.

당신의 사주에서 ${ohengName}(${mainOheng}) 기운이 가장 강하게 나타납니다. ${danceInfo.reason}

${seasonMsg} ${genderTrait}이(가) 돋보이는 당신에게 ${danceInfo.genre}은(는) 천생연분의 춤입니다.`

  const tip = `💡 ${danceInfo.tip}

오늘 ${danceInfo.emoji} ${danceInfo.genre} 파티에 참석하면 특별한 인연을 만날 수 있습니다.`

  return { title, desc, tip }
}

